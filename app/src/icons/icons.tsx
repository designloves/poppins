// Ported from the legacy app's SVG.* string-returning functions into
// real JSX components — actual React elements instead of innerHTML
// strings, so they're type-checked and diffable like any other markup.

interface IconProps {
  size: number
  color: string
}

export function Bloom({
  size,
  color,
  center,
  spinning,
}: IconProps & { center?: string; spinning?: boolean }) {
  const c = center || color
  const petalRotations = [0, 60, 120, 180, 240, 300]
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 32 32"
      style={spinning ? { animation: 'bloom-spin 4s linear infinite' } : undefined}
    >
      {petalRotations.map((d) => (
        <ellipse
          key={d}
          cx="16"
          cy="9"
          rx="4"
          ry="6"
          fill={color}
          transform={`rotate(${d} 16 16)`}
        />
      ))}
      <circle cx="16" cy="16" r="3" fill={c} />
    </svg>
  )
}

